import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { setTimeout as wait } from 'node:timers/promises';
import { samplePdf } from './Workbench_Check_CodexV7.mjs';

export async function runLanguageLifeCheck(win, { documentsDirectory, workbench, life, globalSearch, mirror }) {
  const run = expression => win.webContents.executeJavaScript(expression, true);
  const el = selector => 'document.querySelector(' + JSON.stringify(selector) + ')';
  const click = selector => run(el(selector) + '.click()');
  const value = (selector, next, event = 'input') => run(`(() => {
    const input = ${el(selector)};
    input.value = ${JSON.stringify(next)};
    input.dispatchEvent(new Event(${JSON.stringify(event)}, { bubbles: true }));
  })()`);
  async function until(expression, label, seconds = 20) {
    const deadline = Date.now() + seconds * 1000;
    while (Date.now() < deadline) {
      if (await run(expression)) return;
      await wait(60);
    }
    throw new Error(`V13 定向验收超时（${label}）`);
  }
  const nav = tab => click(`[data-wb-nav="${tab}"]`);
  const language = 'window.stilltimeDesktop.translation';
  const query = '[data-tr-query]';
  const note = await workbench.saveNote({ kind: 'note', title: 'V13 笔记来源', body: 'The voice was stable.' });
  await until(`Boolean(${el('#wb-translation form')} && ${el('#wb-life form')} && ${el('.wb-global-search')})`, '模块挂载');
  await nav('translation');
  await until(`${el('[data-tr-model]')}.value === 'argos'`, 'Argos 本地模型可选', 45);
  assert.ok(await run(`Boolean(${el('[data-tr-source-copy]')} && ${el('[data-tr-source-paste]')} && ${el('[data-tr-result-copy]')} && ${el('[data-tr-output-paste]')})`), '翻译原文和结果区应提供复制、粘贴按钮');
  const suiteClipboard = 'window.stilltimeDesktop.desktopSuite';
  await run(`${suiteClipboard}.writeText('QA pasted text')`);
  await value('[data-tr-source]', 'left|right');
  await run(`${el('[data-tr-source]')}.setSelectionRange(5, 5)`);
  await click('[data-tr-source-paste]');
  await until(`${el('[data-tr-source]')}.value === 'left|QA pasted textright'`, '粘贴到查词原文');
  await run(`${el('[data-tr-source]')}.setSelectionRange(5, 19)`);
  await click('[data-tr-source-copy]');
  await until(`${suiteClipboard}.readText().then(text => text === 'QA pasted text')`, '复制查词原文选区');
  const models = await run(language + '.availableModels()');
  assert.ok(models.models.some(model => model.id === 'argos' && model.directions.length === 2));
  console.log('V13 QA models', models.models.map(model => model.id + ':' + model.directions.join(',')).join(' '));
  await value(query, 'voice');
  await click('[data-tr-lookup-form] [type=submit]');
  await until(`${el('[data-tr-lookup-result]')}.textContent.includes('声音') && ${el('[data-tr-due]')}.textContent.includes('1')`, '英汉查词并自动收录');
  await value(query, '声音');
  await value('[data-tr-translate-direction]', 'zh-en', 'change');
  await click('[data-tr-lookup-form] [type=submit]');
  await until(`${el('[data-tr-lookup-result]')}.textContent.includes('sound; voice')`, '汉英查词');
  await value('[data-tr-term-form] [name=source]', 'voice quality');
  await value('[data-tr-term-form] [name=target]', '嗓音质量');
  await click('[data-tr-term-form] button');
  await until(`${el('[data-tr-terms]')}.textContent.includes('嗓音质量')`, '术语落盘');
  await value('[data-tr-translate-direction]', 'en-zh', 'change');
  await value('[data-tr-source]', 'The patient reported gradual improvement in voice quality.');
  await click('[data-tr-translate]');
  await until(`/\\p{Script=Han}/u.test(${el('[data-tr-output]')}.value)`, '实际本地段落翻译', 120);
  const originalOutput = await run(`${el('[data-tr-output]')}.value`);
  await run(`${suiteClipboard}.writeText(' · QA 粘贴')`);
  await run(`${el('[data-tr-output]')}.setSelectionRange(${el('[data-tr-output]')}.value.length, ${el('[data-tr-output]')}.value.length)`);
  await click('[data-tr-output-paste]');
  await until(`${el('[data-tr-output]')}.value.endsWith(' · QA 粘贴')`, '粘贴到译文');
  await run(`${el('[data-tr-output]')}.setSelectionRange(${el('[data-tr-output]')}.value.lastIndexOf(' · QA 粘贴'), ${el('[data-tr-output]')}.value.length)`);
  await click('[data-tr-result-copy]');
  await until(`${suiteClipboard}.readText().then(text => text === ' · QA 粘贴')`, '复制译文选区');
  assert.ok(originalOutput, '本地翻译应产生可编辑译文');
  console.log('V13 QA dictionary, terms and paragraph');
  assert.equal((await run(language + '.listTerms()'))[0].target, '嗓音质量');
  const phrase = 'The patient reported a gradual improvement in voice quality after completing six weeks of supervised therapy. The clinical team recorded a sustained vowel and a short reading passage in a quiet room. Two independent listeners assessed each sample. The analysts compared the acoustic measures with patient reports and documented sources of uncertainty. They separated the training and evaluation participants before comparing the models. The resulting measurements were reviewed together with the original notes. Additional observations will be collected during the next visit to confirm whether the reported changes remain stable over time in everyday conversations and reading tasks.';
  const samples = [];
  for (const model of models.models.filter(item => item.available && (!process.env.STILLTIME_DEV_ARGOS_ONLY || item.id === 'argos'))) {
    for (const direction of model.directions) {
      const text = direction === 'en-zh' ? phrase : '患者在六周的治疗后报告嗓音质量逐步改善。研究团队将继续记录阅读和日常交谈期间的变化。';
      const result = await run(language + '.translate(' + JSON.stringify({ text, model: model.id, direction }) + ')');
      assert.ok(result.text.trim());
      assert.equal(result.model, model.id);
      assert.match(result.text, direction === 'en-zh' ? /\p{Script=Han}/u : /[A-Za-z]{3}/);
      samples.push({ model: model.id, direction, elapsedMs: Number(result.elapsedMs.toFixed(1)), words: direction === 'en-zh' ? text.split(' ').length : null });
      console.log('V13 QA inference', JSON.stringify(samples.at(-1)));
    }
  }
  await nav('notes');
  await until(`${el('#wb-notes [data-nw-list]')}.textContent.includes('V13 笔记来源')`, '笔记载入');
  await click('#wb-notes [data-nw-list] .note-workspace__archive-open');
  await until(`${el('#wb-notes [data-nw-preview] p')}?.textContent.includes('The voice was stable.')`, 'Markdown 笔记处于阅读模式');
  await run(`(() => {
    const text = ${el('#wb-notes [data-nw-preview] p')}.firstChild;
    const range = document.createRange();
    range.setStart(text, 4);
    range.setEnd(text, 9);
    const selection = window.getSelection();
    selection.removeAllRanges();
    selection.addRange(range);
  })()`);
  await click('#wb-notes [data-nw-translate]');
  await until(`${el('#wb-translation-popup')}.open && ${el(query)}.value === 'voice'`, '笔记选区送入查词');
  await until(`${el('[data-tr-vocabulary]')}.textContent.includes('V13 笔记来源')`, '笔记出处保存');
  const vocabulary = await run(language + '.listVocabulary()');
  const voice = vocabulary.entries.find(entry => entry.word === 'voice');
  assert.ok(voice.sources.some(source => source.noteId === note.id));
  assert.equal(voice.original, 'The voice was stable.');
  await run(language + '.reviewVocabulary(' + JSON.stringify({ id: voice.id, rating: 'good' }) + ')');
  assert.ok((await run(language + '.listVocabulary()')).entries.find(entry => entry.id === voice.id).dueDate);
  await click('[data-translation-close]');
  console.log('V13 QA note selection and review');

  const pdfPath = path.join(path.dirname(documentsDirectory), 'V13-pdf.pdf');
  await writeFile(pdfPath, samplePdf());
  const { items: [pdf] } = await workbench.importFiles([pdfPath]);
  const pdfNote = await workbench.saveNote({ kind: 'note', title: 'V13 PDF 第 2 页', body: '语言学习验收定位', fileId: pdf.id, page: 2 });
  await run(`document.querySelector('[data-global-search-open]').click()`);
  await value('.wb-global-search [data-query]', '语言学习验收定位');
  await until(`${el('.wb-global-result.is-active')}?.textContent.includes('V13 PDF')`, 'PDF 笔记录入索引');
  await click('.wb-global-result.is-active');
  await until(`(() => {
    const span = [...document.querySelectorAll('.workbench-pdf__viewport span')].find(item => item.textContent.startsWith('Acoustic'));
    if (${el('.workbench-pdf__page-input')}?.value !== '2' || !span?.firstChild) return false;
    const range = document.createRange();
    range.setStart(span.firstChild, 0);
    range.setEnd(span.firstChild, 'Acoustic'.length);
    const selection = window.getSelection();
    selection.removeAllRanges();
    selection.addRange(range);
    document.dispatchEvent(new Event('selectionchange'));
    const button = ${el('[data-pdf-translate]')};
    if (!button || button.disabled) return false;
    button.click();
    return true;
  })()`, 'PDF 页码与文本层');
  await until(`!${el('#wb-translation-popup')}.open && ${el('[data-inline-output]')}.textContent.includes('acoustic')`, 'PDF 划词内嵌结果');
  const acoustic = (await run(language + '.listVocabulary()')).entries.find(entry => entry.word === 'acoustic');
  assert.ok(acoustic.sources.some(source => source.fileId === pdf.id && source.page === 2));
  await nav('translation');
  await until(`Boolean(${el(`[data-vocab-id="${acoustic.id}"] [data-vocab-source]`)})`, '生词本中显示 PDF 来源');
  await click(`[data-vocab-id="${acoustic.id}"] [data-vocab-source]`);
  await until(`!${el('#wb-files')}.hidden && ${el('.workbench-pdf__page-input')}?.value === '2'`, '生词跳回 PDF 原页');
  assert.ok(pdfNote.id);
  console.log('V13 QA PDF selection and source jump');

  await nav('life');
  const lifeTab = name => run(`[...document.querySelectorAll('.wb-life-tab')].find(tab => tab.textContent === ${JSON.stringify(name)}).click()`);
  async function saveRecord(name, title, fields) {
    await lifeTab(name);
    await value('[data-life-title]', title);
    for (const [key, text] of Object.entries(fields)) await value(`[data-life-field="${key}"]`, text, key === 'stage' ? 'change' : 'input');
    await click('[data-life-form] [type=submit]');
    await until(`${el('[data-life-records]')}.textContent.includes(${JSON.stringify(title)})`, '保存' + title);
  }
  await saveRecord('生活经历', '现场观察', { happenedAt: '2026-11-14', place: '实验室', event: '记录测试台的噪声。', learning: '提前校准。' });
  await saveRecord('情绪日记', '私密验收记录', { trigger: '隐私隔离样本', feelings: '保持平静' });
  const [mood] = await life.list({ kind: 'mood' });
  assert.match(await readFile(path.join(documentsDirectory, mood.relativePath), 'utf8'), /^private: true$/m);
  await assert.rejects(mirror.share(mood.id, mood.relativePath));
  assert.ok((await globalSearch.query({ query: '隐私隔离样本' })).results.some(item => item.id === mood.id));
  console.log('V13 QA mood privacy and local search');
  await saveRecord('思考页', '分析问题', { question: '怎样提高可靠性？', aiQuestions: '预计有哪些干扰？', conclusion: '先复核样本。' });
  const [thinking] = await life.list({ kind: 'thinking' });
  await assert.rejects(mirror.share(thinking.id, thinking.relativePath), /私密/);
  const approved = await life.save({ ...thinking, private: false, expectedUpdatedAt: thinking.updatedAt });
  const shared = await mirror.share(approved.id, approved.relativePath);
  const mirrored = await readFile(shared.mirrorPath, 'utf8');
  await writeFile(shared.mirrorPath, mirrored.replace('预计有哪些干扰？', '如何区分测量误差和样本差异？'), 'utf8');
  const proposal = (await mirror.list()).find(item => item.id === thinking.id);
  assert.equal(proposal.status, 'pending-review');
  await mirror.review({ id: thinking.id, action: 'accept', expectedSourceHash: proposal.sourceHash, expectedMirrorHash: proposal.mirrorHash });
  assert.match((await life.get({ id: thinking.id, kind: 'thinking' })).fields.aiQuestions, /测量误差和样本差异/);
  await saveRecord('模板', '读书日志模板', { templateBody: '## 摘录\n\n要记录的句子\n\n## 感想' });
  await lifeTab('自定义领域');
  await value('[data-life-title]', '语言学习记录');
  await until(`${el('[data-life-template-select')}.options.length > 1`, '自定义领域模板');
  await run(`${el('[data-life-template-select]')}.selectedIndex = 1`);
  await click('[data-life-use-template]');
  assert.match(await run(`${el('[data-life-field=templateBody]')}.value`), /## 摘录/);
  await value('[data-life-area]', '语言学习');
  await click('[data-life-form] [type=submit]');
  await until(`${el('[data-life-records]')}.textContent.includes('语言学习记录')`, '创建自定义领域卡片');
  await nav('notes');
  await click('#wb-notes [data-nw-new]');
  await run(`${el('#wb-notes .wb-note-template')}.open = true`);
  await until(`${el('#wb-notes .wb-note-template select')}.options.length > 1`, '载入自定义模板');
  const noteBody = '#wb-notes [data-nw-body]';
  await value(noteBody, '之前内容\n\n之后内容');
  await run(`${el(noteBody)}.setSelectionRange('之前内容\\n\\n'.length, '之前内容\\n\\n'.length)`);
  await run(`(() => { const select = ${el('#wb-notes .wb-note-template select')}; select.selectedIndex = 1; select.dispatchEvent(new Event('change', { bubbles: true })); })()`);
  await until(`${el(noteBody)}.value.includes('## 摘录')`, '选择模板后插入笔记');
  const insertedBody = await run(`${el(noteBody)}.value`);
  assert.ok(insertedBody.startsWith('之前内容\n\n## 摘录'), '模板应插入当前光标位置');
  assert.ok(insertedBody.endsWith('## 感想\n\n之后内容'), '模板插入应保留光标两侧原文');
  assert.ok(await run(`${el('#wb-notes .wb-note-template button')}.hidden`), '笔记选中模板后应自动插入');
  await click('#wb-notes [data-nw-save]');
  await click('#wb-notes [data-nw-metadata] [type=submit]');
  await until(`!${el('#wb-notes [data-nw-metadata]')}.open`, '笔记模板实际写入');

  await nav('settings');
  await until(`${el('#wb-settings .wb-settings__workspace')}.textContent.includes('Markdown 模板')`, '模板管理设置页');
  await click('#wb-settings [data-template-new]');
  await value('#wb-settings [data-template-title]', '设置页模板验收');
  await value('#wb-settings [data-template-body]', '## 初始内容\n\n首次保存。');
  await click('#wb-settings [data-template-form] [type=submit]');
  await until(`${el('#wb-settings [data-template-list]')}.textContent.includes('设置页模板验收')`, '设置页创建模板');
  await run(`[...document.querySelectorAll('#wb-settings .wb-settings__template-item')].find(button => button.textContent.includes('设置页模板验收')).click()`);
  await value('#wb-settings [data-template-title]', '设置页模板验收（已编辑）');
  await value('#wb-settings [data-template-body]', '## 更新内容\n\n设置页修改后保存。');
  await click('#wb-settings [data-template-form] [type=submit]');
  await until(`${el('#wb-settings [data-template-list]')}.textContent.includes('设置页模板验收（已编辑）')`, '设置页编辑模板');
  const editedTemplate = (await life.list({ kind: 'template' })).find(item => item.title === '设置页模板验收（已编辑）');
  assert.ok(editedTemplate, '设置页编辑应写回现有 Markdown 模板记录');
  assert.match(editedTemplate.fields.templateBody, /## 更新内容/);
  console.log('V13 QA settings template create and edit');

  await nav('home');
  const homeSource = '[data-home-tr-source]';
  const homeOutput = '[data-home-tr-output]';
  const homeModel = '[data-home-tr-model]';
  const homeStatus = '[data-home-tr-status]';
  await value(homeSource, 'The patient reported gradual improvement in voice quality.');
  await until(`${el(homeModel)}.value === 'argos'`, '首页可用的本地模型', 45);
  await click('[data-home-tr-submit]');
  await until(`/\\p{Script=Han}/u.test(${el(homeOutput)}.value)`, '首页英译中', 120);
  assert.match(await run(`${el('[data-home-tr-terms]')}.textContent`), /嗓音质量/);
  const englishResult = await run(`${el(homeOutput)}.value`);
  await click('[data-home-tr-result-copy]');
  await until(`${suiteClipboard}.readText().then(text => text === ${JSON.stringify(englishResult)})`, '首页复制译文');
  await value(homeOutput, '');
  await click('[data-home-tr-result-paste]');
  await until(`${el(homeOutput)}.value === ${JSON.stringify(englishResult)}`, '首页粘贴译文');
  const chinese = '研究团队将继续记录阅读期间的变化。';
  await run(`${suiteClipboard}.writeText(${JSON.stringify(chinese)})`);
  await value(homeSource, '');
  await click('[data-home-tr-source-paste]');
  await until(`${el(homeSource)}.value === ${JSON.stringify(chinese)}`, '首页粘贴原文');
  await click('[data-home-tr-source-copy]');
  await until(`${el(homeStatus)}.textContent === '已复制原文'`, '首页复制原文');
  await value('[data-home-tr-direction]', 'zh-en', 'change');
  const alternative = models.models.find(item => item.id === 'opus' && item.directions.includes('zh-en'));
  if (alternative) await value(homeModel, alternative.id, 'change');
  await click('[data-home-tr-submit]');
  await until(`${el(homeStatus)}.textContent === '本地翻译完成' && /[A-Za-z]{3}/.test(${el(homeOutput)}.value)`, '首页中译英', 120);
  const chineseResult = await run(`${el(homeOutput)}.value`);
  await nav('translation');
  await nav('home');
  assert.deepEqual(await run(`[${el(homeSource)}.value, ${el(homeOutput)}.value, ${el(homeModel)}.value]`),
    [chinese, chineseResult, alternative?.id || 'argos'], '页面切换保留原文、译文和模型');
  await value('[data-home-tr-direction]', 'auto', 'change');
  await value(homeSource, 'voice');
  await click('[data-home-tr-submit]');
  await until(`${el(homeOutput)}.value.includes('声音') && ${el(homeStatus)}.textContent.includes('生词本')`, '首页真实词典查询');
  console.log('V13 QA home translation card, bilingual inference, model selection, dictionary and clipboard');
  await nav('life');
  await saveRecord('内容看板', '短视频选题', { stage: 'topic', topic: '用图解介绍工作流程。' });
  const [topic] = await life.list({ kind: 'content' });
  const card = `[data-record-id="${topic.id}"]`;
  await run(`${el(card)}.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true, cancelable: true }))`);
  await until(`Boolean(${el('[data-stage=script] ' + card)})`, '看板键盘推进到脚本');
  assert.equal((await life.get({ id: topic.id })).status, 'script');
  const warmLookup = await run(language + '.lookup({text:"pathological",direction:"en-zh"})');
  const report = { bilingualLookup: true, noteSelection: true, pdfPage: 2, review: true, terms: true, moodPrivate: true,
    templates: true, templateSettings: true, templateCursorInsertion: true, translationClipboardControls: true,
    translationClipboardActions: true,
    customArea: true, thinkingReviewed: true, contentBoard: true, warmLookupMs: warmLookup.elapsedMs, samples };
  await writeFile(path.join(path.dirname(documentsDirectory), 'language-life-verification.json'), JSON.stringify(report, null, 2));
  console.log('LANGUAGE_LIFE_VERIFY_OK', JSON.stringify(report));
}
