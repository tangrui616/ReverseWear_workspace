import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { commands, events, suiteOperations } from './contract.mjs';

const sourceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contractSource = await readFile(path.join(sourceRoot, 'ipc/contract.mjs'), 'utf8');
const mainProcess = await readFile(path.join(sourceRoot, 'main.mjs'), 'utf8');
const suiteMain = await readFile(path.join(sourceRoot, 'desktop_suite/windowManager.mjs'), 'utf8');
const windowChrome = await readFile(path.join(sourceRoot, 'desktop_window_chrome.mjs'), 'utf8');
const mainModules = await readdir(path.join(sourceRoot, 'main'), { withFileTypes: true })
  .then(items => Promise.all(items.filter(item => item.isFile() && item.name.endsWith('.mjs'))
    .map(item => readFile(path.join(sourceRoot, 'main', item.name), 'utf8'))));
const handlerSources = [mainProcess, ...mainModules];
const templates = [
  ['preload.cjs', 'ipc/templates/preload.cjs'],
  ['capture-preload.cjs', 'ipc/templates/capture-preload.cjs'],
  ['suite-preload.cjs', 'ipc/templates/suite-preload.cjs'],
];
const channelPattern = /ipcRenderer\.(invoke|on|removeListener)\(\s*channels\[(['"])([^'"]+)\2\]/g;

function typeMapKeys(name) {
  const marker = '}} ' + name;
  const end = contractSource.indexOf(marker);
  if (end < 0) throw new Error('Missing JSDoc type map: ' + name);
  const start = contractSource.lastIndexOf('@typedef {{', end);
  if (start < 0) throw new Error('Unterminated JSDoc type map: ' + name);
  return new Set([...contractSource.slice(start, end).matchAll(/^\s*\*\s+'([^']+)':/gm)].map(match => match[1]));
}

function assertExactTypeKeys(name, expectedKeys) {
  const actual = typeMapKeys(name);
  const expected = new Set(expectedKeys);
  const missing = [...expected].filter(key => !actual.has(key));
  const extra = [...actual].filter(key => !expected.has(key));
  if (missing.length || extra.length) {
    throw new Error(name + ' coverage mismatch. Missing: ' + missing.join(', ') + '. Extra: ' + extra.join(', '));
  }
}

assertExactTypeKeys('CommandArgumentMap', Object.keys(commands));
assertExactTypeKeys('CommandResultMap', Object.keys(commands));
assertExactTypeKeys('EventPayloadMap', Object.keys(events));
assertExactTypeKeys('SuiteOperationArgumentMap', Object.keys(suiteOperations));
assertExactTypeKeys('SuiteOperationResultMap', Object.keys(suiteOperations));

function compile(template, file) {
  const usedCommands = new Set();
  const usedEvents = new Set();
  const channels = {};
  for (const [, method, , key] of template.matchAll(channelPattern)) {
    const table = method === 'invoke' ? commands : events;
    if (!Object.hasOwn(table, key)) throw new Error(file + ' references an undeclared IPC key: ' + key);
    (method === 'invoke' ? usedCommands : usedEvents).add(key);
    channels[key] = table[key].channel;
  }
  const header = '/* Generated by ipc/generate-preloads.mjs. Edit the template and contract instead. */\n'
    + 'const channels = Object.freeze(' + JSON.stringify(channels, null, 2) + ');\n';
  return { content: header + template, usedCommands, usedEvents };
}

const checkOnly = process.argv.includes('--check');
const writeFiles = process.argv.includes('--write');
if (checkOnly === writeFiles) {
  throw new Error('Use exactly one of --write or --check.');
}

const invoked = new Set();
const subscribed = new Set();
for (const [outputName, templateName] of templates) {
  const template = await readFile(path.join(sourceRoot, templateName), 'utf8');
  const { content, usedCommands, usedEvents } = compile(template, outputName);
  for (const key of usedCommands) invoked.add(key);
  for (const key of usedEvents) subscribed.add(key);
  const outputPath = path.join(sourceRoot, outputName);
  if (writeFiles) {
    await writeFile(outputPath, content, 'utf8');
  } else {
    const actual = await readFile(outputPath, 'utf8');
    if (actual !== content) throw new Error(outputName + ' is stale. Run node ipc/generate-preloads.mjs --write.');
  }
}

const uncovered = Object.keys(commands).filter(key => !invoked.has(key));
if (uncovered.length) {
  throw new Error('Commands with no preload invocation: ' + uncovered.join(', '));
}
const unsubscribed = Object.keys(events).filter(key => !subscribed.has(key));
if (unsubscribed.length) throw new Error('Events with no preload subscription: ' + unsubscribed.join(', '));

const registeredCommands = new Set();
for (const source of handlerSources) {
  for (const match of source.matchAll(/register\('([^']+)'/g)) {
    const key = match[1];
    if (registeredCommands.has(key)) throw new Error('Duplicate main IPC handler: ' + key);
    registeredCommands.add(key);
  }
}
if (!suiteMain.includes("ipcMain.handle(commands['suite:invoke'].channel")) {
  throw new Error('The suite IPC handler must register the shared command channel.');
}
registeredCommands.add('suite:invoke');
const unlistedHandlers = [...registeredCommands].filter(key => !(key in commands));
const unusedCommands = Object.keys(commands).filter(key => !registeredCommands.has(key));
if (unlistedHandlers.length || unusedCommands.length) {
  throw new Error('Main IPC/contract mismatch. Unlisted handlers: ' + unlistedHandlers.join(', ')
    + '. Unused contract entries: ' + unusedCommands.join(', '));
}
const router = handlerSources.find(source => source.includes('export function createHandlerRegistry'));
if (!router || !router.includes('command.write') || !router.includes('command.capturePopup')) {
  throw new Error('IPC router must apply write and capture-popup policies from the command contract.');
}

const sentEvents = new Set();
for (const source of [...handlerSources, suiteMain, windowChrome]) {
  for (const match of source.matchAll(/webContents\.send\('stilltime:([^']+)'/g)) sentEvents.add(match[1]);
  for (const match of source.matchAll(/sendEvent\([^,]+,\s*['"]([^'"]+)['"]/g)) sentEvents.add(match[1]);
}
const unlistedEvents = [...sentEvents].filter(key => !(key in events));
const unusedEvents = Object.keys(events).filter(key => !sentEvents.has(key));
if (unlistedEvents.length || unusedEvents.length) {
  throw new Error('IPC event/contract mismatch. Unlisted events: ' + unlistedEvents.join(', ')
    + '. Unused event entries: ' + unusedEvents.join(', '));
}

if (!suiteMain.includes('suiteOperations[operation]?.roles.includes(context.role)')) {
  throw new Error('Suite invocation must authorize operations through suiteOperations and the window role.');
}
const handlers = suiteMain.split('const handlers = {')[1]?.split('\n  };')[0] ?? '';
const declaredSuiteOperations = new Set([...handlers.matchAll(/^\s*'([^']+)':/gm)].map(match => match[1]));
const suiteContractOperations = Object.keys(suiteOperations);
const unlistedSuiteOperations = [...declaredSuiteOperations].filter(key => !Object.hasOwn(suiteOperations, key));
const unusedSuiteOperations = suiteContractOperations.filter(key => !declaredSuiteOperations.has(key));
if (unlistedSuiteOperations.length || unusedSuiteOperations.length) {
  throw new Error('Suite operation/contract mismatch. Unlisted: ' + unlistedSuiteOperations.join(', ')
    + '. Unused: ' + unusedSuiteOperations.join(', '));
}

console.log('IPC preload ' + (writeFiles ? 'generation' : 'check') + ' passed.');
